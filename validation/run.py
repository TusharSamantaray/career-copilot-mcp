"""Run every validation case and update the scoreboard.

    uv run validation/run.py           # run, update RESULTS.md and HISTORY.md
    uv run validation/run.py --check   # run only; exit 1 if any case fails

Each case in validation/cases/ replays one improvement with made-up
people and measures it. RESULTS.md shows the latest numbers; HISTORY.md
gains a dated row only when a case's score changes, so the file shows
when each improvement landed. Synthetic data only, in a throwaway folder.
"""
import importlib
import os
import pkgutil
import shutil
import sys
import tempfile
from datetime import date

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
WORK = tempfile.mkdtemp(prefix="cc-validation-")
os.environ["COPILOT_DATA_DIR"] = WORK          # before copilot is imported
for name in ("DATABASE_URL", "CAREER_COPILOT_MASTER_KEY"):
    os.environ.pop(name, None)
sys.path[:0] = [ROOT, HERE]

import cases  # noqa: E402


def version():
    with open(os.path.join(ROOT, "pyproject.toml"), encoding="utf-8") as f:
        for line in f:
            if line.startswith("version"):
                return line.split("=", 1)[1].strip().strip('"')
    return "?"


def run_case(module):
    rows = []

    def measure(metric, measured, expected):
        rows.append({"metric": metric, "measured": measured,
                     "expected": expected, "ok": measured == expected})

    try:
        module.run(f"validation-{module.ID}", measure)
    except Exception as exc:                       # a crash is a failure
        rows.append({"metric": "runs without error", "measured":
                     type(exc).__name__, "expected": "no error",
                     "ok": False})
    return rows


def _fmt(value):
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, tuple):
        return " -> ".join(_fmt(v) for v in value)
    if isinstance(value, list):
        return ", ".join(map(str, value)) or "none"
    return str(value)


def results_md(found, today, ver):
    out = ["# Validation results", "",
           f"Last run {today}, version {ver}. Made-up people only. "
           "Regenerated by `uv run validation/run.py`; see "
           "[README.md](README.md).", ""]
    for module, rows in found:
        passed = sum(r["ok"] for r in rows)
        out += [f"## {module.TITLE} ({module.BACKLOG})", "",
                f"Before: {module.BEFORE}", "",
                f"Score: {passed}/{len(rows)}", "",
                "| Measure | Expected | Measured | |", "|---|---|---|---|"]
        out += [f"| {r['metric']} | {_fmt(r['expected'])} | "
                f"{_fmt(r['measured'])} | {'pass' if r['ok'] else 'FAIL'} |"
                for r in rows]
        out.append("")
    return "\n".join(out)


def update_history(found, today, ver):
    path = os.path.join(HERE, "HISTORY.md")
    with open(path, encoding="utf-8") as f:
        text = f.read()
    last = {}
    for line in text.splitlines():
        cells = [c.strip() for c in line.strip("|").split("|")]
        if len(cells) == 5 and cells[0][:2] == "20":
            last[cells[2]] = cells[4]
    new = []
    for module, rows in found:
        score = f"{sum(r['ok'] for r in rows)}/{len(rows)}"
        if last.get(module.ID) != score:
            new.append(f"| {today} | {ver} | {module.ID} | {module.BACKLOG} "
                       f"| {score} |")
    if new:
        with open(path, "a", encoding="utf-8") as f:
            f.write("\n".join(new) + "\n")
    return len(new)


def main():
    check_only = "--check" in sys.argv
    found = []
    for info in sorted(pkgutil.iter_modules(cases.__path__),
                       key=lambda i: i.name):
        module = importlib.import_module(f"cases.{info.name}")
        found.append((module, run_case(module)))
    failed = 0
    for module, rows in found:
        passed = sum(r["ok"] for r in rows)
        print(f"{module.ID} ({module.BACKLOG}): {passed}/{len(rows)}")
        for r in rows:
            if not r["ok"]:
                failed += 1
                print(f"  FAIL {r['metric']}: expected {_fmt(r['expected'])}"
                      f", measured {_fmt(r['measured'])}")
    shutil.rmtree(WORK, ignore_errors=True)
    if not check_only:
        today, ver = date.today().isoformat(), version()
        with open(os.path.join(HERE, "RESULTS.md"), "w",
                  encoding="utf-8") as f:
            f.write(results_md(found, today, ver))
        print(f"history rows added: {update_history(found, today, ver)}")
    print("ALL PASSED" if not failed else f"{failed} FAILED")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
